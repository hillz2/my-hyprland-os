#!/usr/bin/env bash
# Build and install the out-of-tree AIC8800 USB Wi-Fi driver into the image.
#
# Hardware: Tenda U11, AX913B and other AIC8800D80-based Wi-Fi 6 adapters.
# Upstream: https://github.com/shenmintao/aic8800d80
#
# This runs during the BlueBuild image build (GitHub Actions), so the module is
# compiled against the exact kernel that ships in the image. Because the image
# is rebuilt on a schedule and on every push, a kernel update automatically
# gets a matching module -- no DKMS/akmod rebuild after `rpm-ostree upgrade`.
#
# Hardware revision note: if the adapter's kernel log reports `chip_mcu_id=1`,
# use a commit from upstream's `legacy-mcu1` branch (matched firmware/loader)
# instead. Override the ref without editing this file, e.g.
#   AIC8800_REF=legacy-mcu1 ./install_aic8800d80.sh
# or run the "aic8800d80 driver" workflow with the `ref` input set.
set -euo pipefail

DRIVER_REPO="${AIC8800_REPO:-https://github.com/shenmintao/aic8800d80.git}"
# Pinned for reproducible image builds. `main` as of 2026-11-20.
DRIVER_REF="${AIC8800_REF:-1a2ce4e38e678a0c0d7f6071be415ab74f488240}"

SRC_DIR=/tmp/aic8800d80

# `uname -r` inside the build container is the *runner* kernel, not the kernel
# that will ship in the image. Ask RPM instead.
mapfile -t KERNELS < <(rpm -q kernel --qf '%{VERSION}-%{RELEASE}.%{ARCH}\n' 2>/dev/null | sort -V)
if [ "${#KERNELS[@]}" -eq 0 ]; then
    # Some minimal images ship only kernel-core without the meta package.
    mapfile -t KERNELS < <(rpm -q kernel-core --qf '%{VERSION}-%{RELEASE}.%{ARCH}\n' 2>/dev/null | sort -V)
fi
if [ "${#KERNELS[@]}" -eq 0 ]; then
    echo "CRITICAL: no kernel package found; cannot build the AIC8800 driver"
    exit 1
fi
KVER="${KERNELS[-1]}"
if [ "${#KERNELS[@]}" -gt 1 ]; then
    echo "WARNING: multiple kernels installed; building only for ${KVER}"
fi
KDIR="/usr/src/kernels/${KVER}"

echo "--- AIC8800D80: building for kernel ${KVER} ---"

# Remember what the image already ships so the toolchain can be removed again
# afterwards without touching pre-installed packages.
PREINSTALLED="$(rpm -q --qf '%{NAME}\n' \
    gcc make bc elfutils-libelf-devel openssl-devel kernel-devel 2>/dev/null || true)"

# kernel-devel must match the installed kernel exactly. Do not let dnf upgrade
# the kernel here: the image's initramfs is generated by the base image, so a
# surprise kernel bump inside the build would leave it stale.
if ! dnf install -y --setopt=install_weak_deps=False \
        gcc make git bc elfutils-libelf-devel openssl-devel "kernel-devel-${KVER}"; then
    echo "Exact kernel-devel-${KVER} is not in the enabled repos; trying the updates archive"
    dnf install -y --enablerepo=fedora-updates-archive --setopt=install_weak_deps=False \
        "kernel-devel-${KVER}"
fi

if [ ! -d "${KDIR}" ]; then
    echo "CRITICAL: ${KDIR} is missing; kernel-devel-${KVER} could not be installed"
    exit 1
fi

rm -rf "${SRC_DIR}"
git clone --quiet --no-checkout "${DRIVER_REPO}" "${SRC_DIR}"
git -C "${SRC_DIR}" checkout --quiet "${DRIVER_REF}"
echo "--- Driver source: $(git -C "${SRC_DIR}" rev-parse --short HEAD) ---"

echo "--- Compiling aic8800_fdrv, aic_load_fw and aic_zlp_quirk ---"
make -C "${SRC_DIR}/drivers/aic8800" KVER="${KVER}" KDIR="${KDIR}" clean
make -C "${SRC_DIR}/drivers/aic8800" KVER="${KVER}" KDIR="${KDIR}" -j"$(nproc)"

WIFI_MODDIR="/usr/lib/modules/${KVER}/kernel/drivers/net/wireless/aic8800"
BT_MODDIR="/usr/lib/modules/${KVER}/kernel/drivers/bluetooth/aic8800"

install -D -m 0644 \
    "${SRC_DIR}/drivers/aic8800/aic8800_fdrv/aic8800_fdrv.ko" \
    "${WIFI_MODDIR}/aic8800_fdrv.ko"
install -D -m 0644 \
    "${SRC_DIR}/drivers/aic8800/aic_load_fw/aic_load_fw.ko" \
    "${WIFI_MODDIR}/aic_load_fw.ko"
install -D -m 0644 \
    "${SRC_DIR}/drivers/aic8800/aic_zlp_quirk/aic_zlp_quirk.ko" \
    "${BT_MODDIR}/aic_zlp_quirk.ko"

# Firmware: upstream warns that stale aic8800* firmware can hang the machine.
echo "--- Installing firmware, udev rule and usb_modeswitch config ---"
rm -rf /usr/lib/firmware/aic8800*
cp -a "${SRC_DIR}"/fw/aic8800* /usr/lib/firmware/

install -D -m 0644 "${SRC_DIR}/aic.rules" \
    /usr/lib/udev/rules.d/90-aic8800-mode-switch.rules
install -D -m 0644 "${SRC_DIR}/usb_modeswitch/1111_1111" \
    "/etc/usb_modeswitch.d/1111:1111"

depmod -a "${KVER}"

echo "--- Verifying ---"
modinfo -F vermagic "${WIFI_MODDIR}/aic8800_fdrv.ko"
if command -v modprobe >/dev/null 2>&1; then
    modprobe -S "${KVER}" --show-depends aic8800_fdrv || true
fi

# Drop the build toolchain again; this image is meant to stay lean. Only
# packages that were not already present are removed.
REMOVE=()
for pkg in gcc make bc elfutils-libelf-devel openssl-devel kernel-devel; do
    if ! grep -qxF "${pkg}" <<<"${PREINSTALLED}"; then
        REMOVE+=("${pkg}")
    fi
done
if [ "${#REMOVE[@]}" -gt 0 ]; then
    echo "--- Removing build-only packages: ${REMOVE[*]} ---"
    dnf remove -y "${REMOVE[@]}" || true
fi

echo "OK: AIC8800D80 driver installed for kernel ${KVER}"
